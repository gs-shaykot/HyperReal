export async function seedOctoberData() {
    for (const user of octoberUsers) {
        await prisma.user.upsert({
            where: { email: user.email },
            update: {
                name: user.name,
                PhotoUrl: user.PhotoUrl,
                role: Role.USER,
                isVerified: true,
                isNewUser: false,
                authProvider: AuthProvider.EMAIL,
            },
            create: {
                id: user.id,
                name: user.name,
                email: user.email,
                password: octoberPasswordHash,
                PhotoUrl: user.PhotoUrl,
                role: Role.USER,
                createdAt: new Date(user.createdAt),
                isVerified: true,
                otp: null,
                otpExpiry: null,
                isNewUser: false,
                phone: user.phone,
                authProvider: AuthProvider.EMAIL,
                marketingNotifications: false,
                orderNotifications: true,
            },
        });
    }

    for (const order of octoberOrders) {
        const existingOrder = await prisma.order.findUnique({
            where: { id: order.id },
            select: { id: true },
        });

        if (existingOrder) {
            continue;
        }

        await prisma.order.create({
            data: {
                id: order.id,
                userId: order.userId,
                status: order.status,
                orderCode: order.orderCode,
                createdAt: new Date(order.createdAt),

                orderItems: {
                    create: order.items,
                },

                payments: {
                    create: order.payment,
                },
            },
        });
    }

    console.log("October 2026 dummy data seeded.");
}
